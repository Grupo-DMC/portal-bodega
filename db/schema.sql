-- Esquema propuesto para SQL Server (referencia para reemplazar los datos ficticios).
-- Reglas clave: stock nunca negativo (CHECK), productos se desactivan (no se borran),
-- cada cambio de stock deja un registro en Movimiento (kardex).

CREATE TABLE Familia      (Cod NVARCHAR(10) PRIMARY KEY, Nombre NVARCHAR(80) NOT NULL, [Desc] NVARCHAR(200) NOT NULL DEFAULT '', Activo BIT NOT NULL DEFAULT 1);
CREATE TABLE Subfamilia   (Cod NVARCHAR(10) PRIMARY KEY, Nombre NVARCHAR(80) NOT NULL, FamCod NVARCHAR(10) NOT NULL REFERENCES Familia(Cod), Activo BIT NOT NULL DEFAULT 1);
CREATE TABLE Bodega       (Cod NVARCHAR(10) PRIMARY KEY, Nombre NVARCHAR(80) NOT NULL, Dir NVARCHAR(200) NOT NULL DEFAULT '', Resp NVARCHAR(80) NOT NULL DEFAULT '', Activo BIT NOT NULL DEFAULT 1);

CREATE TABLE Producto (
  Cod NVARCHAR(30) PRIMARY KEY, [Desc] NVARCHAR(200) NOT NULL,
  FamCod NVARCHAR(10) NOT NULL REFERENCES Familia(Cod), SubCod NVARCHAR(10) NULL REFERENCES Subfamilia(Cod),
  Um NVARCHAR(4) NOT NULL DEFAULT 'UN', Formato NVARCHAR(60) NOT NULL DEFAULT '',
  Inventariable BIT NOT NULL DEFAULT 1, Critico INT NOT NULL DEFAULT 0 CHECK (Critico >= 0),
  Transito INT NOT NULL DEFAULT 0, UltIngreso DATE NULL, Activo BIT NOT NULL DEFAULT 1,
  MedTipo NVARCHAR(10) NULL, MedL DECIMAL(10,2) NULL, MedA DECIMAL(10,2) NULL, MedH DECIMAL(10,2) NULL, MedU NVARCHAR(2) NULL,
  Peso DECIMAL(10,2) NULL, PesoU NVARCHAR(2) NULL
);

CREATE TABLE Stock (
  ProdCod NVARCHAR(30) NOT NULL REFERENCES Producto(Cod), BodCod NVARCHAR(10) NOT NULL REFERENCES Bodega(Cod),
  Disponible INT NOT NULL DEFAULT 0 CHECK (Disponible >= 0),
  EnRevision INT NOT NULL DEFAULT 0 CHECK (EnRevision >= 0),
  Danado INT NOT NULL DEFAULT 0 CHECK (Danado >= 0),
  PRIMARY KEY (ProdCod, BodCod)
);

CREATE TABLE Cotizacion (
  Id NVARCHAR(20) PRIMARY KEY, Cliente NVARCHAR(120) NOT NULL, Rut NVARCHAR(14) NOT NULL, Ejecutivo NVARCHAR(80) NOT NULL,
  FAprobacion DATE NOT NULL, FVence DATE NOT NULL,
  Estado NVARCHAR(12) NOT NULL CHECK (Estado IN ('Pendiente','Parcial','Completa','Vencida','Cerrada')), Obs NVARCHAR(400) NOT NULL DEFAULT ''
);
CREATE TABLE CotizacionItem (
  CotId NVARCHAR(20) NOT NULL REFERENCES Cotizacion(Id), ProdCod NVARCHAR(30) NOT NULL REFERENCES Producto(Cod),
  Cantidad INT NOT NULL CHECK (Cantidad > 0), Despachado INT NOT NULL DEFAULT 0,
  PRIMARY KEY (CotId, ProdCod), CHECK (Despachado BETWEEN 0 AND Cantidad)
);

CREATE TABLE Despacho (
  Id NVARCHAR(12) PRIMARY KEY, CotId NVARCHAR(20) NOT NULL REFERENCES Cotizacion(Id), Fecha DATE NOT NULL, Hora CHAR(5) NOT NULL,
  Guia NVARCHAR(30) NOT NULL DEFAULT '', OC NVARCHAR(30) NOT NULL DEFAULT '', HEP NVARCHAR(30) NOT NULL DEFAULT '',
  Usuario NVARCHAR(80) NOT NULL, Obs NVARCHAR(400) NOT NULL DEFAULT '',
  CHECK (Guia <> '' OR OC <> '' OR HEP <> '')
);
CREATE TABLE DespachoLinea (DespId NVARCHAR(12) NOT NULL REFERENCES Despacho(Id), ProdCod NVARCHAR(30) NOT NULL, BodCod NVARCHAR(10) NOT NULL, Cantidad INT NOT NULL CHECK (Cantidad > 0));

CREATE TABLE Movimiento (
  Id BIGINT IDENTITY PRIMARY KEY, Fecha DATE NOT NULL, Hora CHAR(5) NOT NULL,
  Tipo NVARCHAR(20) NOT NULL, ProdCod NVARCHAR(30) NOT NULL REFERENCES Producto(Cod), Cantidad INT NOT NULL, BodCod NVARCHAR(10) NOT NULL,
  Documento NVARCHAR(120) NOT NULL DEFAULT '', CotId NVARCHAR(20) NOT NULL DEFAULT '', Cliente NVARCHAR(120) NOT NULL DEFAULT '',
  Motivo NVARCHAR(400) NOT NULL DEFAULT '', Usuario NVARCHAR(80) NOT NULL, Saldo INT NOT NULL
);
CREATE INDEX IX_Movimiento_Prod ON Movimiento (ProdCod, Fecha DESC);

CREATE TABLE Usuario (Username NVARCHAR(32) PRIMARY KEY, Nombre NVARCHAR(80) NOT NULL, Rol NVARCHAR(12) NOT NULL CHECK (Rol IN ('Admin','Bodeguero','Ventas')), Email NVARCHAR(120) NOT NULL, PasswordHash VARBINARY(64) NOT NULL, Salt VARBINARY(16) NOT NULL, Activo BIT NOT NULL DEFAULT 1);
